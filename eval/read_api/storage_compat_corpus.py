@dataclass(frozen=True)
class CaseSpec:
    """One synthetic Trial, shaped so the production helpers accept it."""

    target_id: str
    target_run_id: str
    trial_id: str
    project_id: str
    eval_sha: str
    stack_fingerprint: str
    terminal: str
    start_phase: str
    phases: tuple[tuple[str, str, str], ...]
    verdicts: tuple[demo.VerdictSpec, ...]
    diagnoses: tuple[dict, ...] = ()
    # schema_version 1 is the historical case: no project snapshot sections.
    schema_version: int = 2
    # Only the complete Trial captured its project snapshot before teardown.
    capture_snapshot: bool = False
    # Pod exports this case's pods reached; the interrupted Trial reached none.
    pod_exports: tuple[PodExportSpec, ...] = ()
    with_skill: bool = False
    produced_hunt_config: bool = False
    consumed_test_spec: bool = False

    @property
    def instance_id(self) -> str:
        return INSTANCE_ID


