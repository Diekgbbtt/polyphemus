@dataclass(frozen=True)
class Roots:
    """The four synthetic roots, and the environment the read API needs."""

    root: Path
    store: Path
    raw: Path
    runs: Path
    legacy_runs: Path

    def environment(self) -> dict[str, str]:
        return {
            "EVAL_ARTIFACT_STORE": str(self.store),
            "EVAL_PROJECT_DATA_ROOT": str(self.raw),
            "EVAL_RUNS_ROOT": str(self.runs),
            "EVAL_RUNS_LEGACY_ROOT": str(self.legacy_runs),
            "EVAL_DATASET_ID": DATASET_ID,
            "EVAL_DATASET_NAME": DATASET_NAME,
            "EVAL_INSTANCE_ID": INSTANCE_ID,
        }


def roots_for(root: str | Path) -> Roots:
    base = Path(root)
    return Roots(
        root=base,
        store=base / "store",
        raw=base / "raw",
        runs=base / "runs",
        legacy_runs=base / "runs-legacy",
    )


