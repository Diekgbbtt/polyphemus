"""A synthetic *storage-compatibility* corpus for the eval read API.

The demo store exercise the whole dashboard end-to-end, without waiting for a
new evaluation, against the FOUR sources the read API now reads:

    <root>/store        the materialized store        -> EVAL_ARTIFACT_STORE
    <root>/raw          the persistent project root   -> EVAL_PROJECT_DATA_ROOT
    <root>/runs         the primary runs root         -> EVAL_RUNS_ROOT
    <root>/runs-legacy  the historical runs root      -> EVAL_RUNS_LEGACY_ROOT

Every identifier is `demo-*` and the dataset is clearly labelled synthetic. No
real store, raw data, Neo4j graph or benchmark checkout is ever read or written;
the generator only touches the four roots under the directory it is given.

The corpus carries three cases - a complete Trial, an interrupted Trial and a
historical schema-v1 Trial - built with the production helpers (allowlist
collection, graph capture, manifest building), so ids, digests, counts and
hashes are derived, never hand-authored. `generate` is deterministic and
idempotent and never removes anything it did not write; `refresh` is a separate,
explicit action that adds one new materialized Trial, one new allowlisted
artifact and one new/updated spend record, so a later request sees them without
an API restart.
"""
