"""A synthetic, *self-contained* eval store for the /eval demo pages (#278).

Every artifact written here is FAKE: the dataset, the verdicts, the diagnoses,
the evidence files, the SHAs, and the fingerprints. It exists so the `/eval`
pages can be exercised end-to-end without running a real Trial, and it never
reads from a real run.

The tree mirrors what the materializer produces, not just what the UI reads:
each complete trial carries a manifest built by the real
`orchestrator.store.build_run_manifest`, its `chain_sources` list exactly the
unique evidence references its verdicts name, and every referenced hunt config,
spec family, experiment log and pod export really exists under that trial - at
the same relative paths `orchestrator.files` addresses. Verdicts and diagnoses
are validated by the production readers.

`white-jotter-1/run-demo-b/trial-2` is deliberately broken: it is a *failure
injection* (an interrupted run whose `verdicts.yaml` was never materialized),
kept so the degraded path stays exercised. It is not the output of a successful
materialization, and the generator writes no chain for it.

The generator is deterministic and idempotent - it writes only the demo files it
knows, and never removes, truncates, or rewrites anything else in the output
directory. Run it with:

    PYTHONPATH=eval .venv/bin/python -m read_api.demo_data \
        --output /tmp/polyphemus-eval-demo
"""
