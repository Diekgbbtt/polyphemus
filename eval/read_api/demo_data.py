def generate(output: str | Path) -> Path:
    """Write the demo store under `output`; return the created root.

    Idempotent and non-destructive: the same input yields byte-identical files,
    and anything the generator does not itself write is left untouched.
    """
    root = Path(output)
    files = artifact_files.FileStore()
    for spec in demo_trials():
        trial_dir = root / spec.target_id / spec.target_run_id / spec.trial_id
        trial_dir.mkdir(parents=True, exist_ok=True)

        rows: list[dict] = []
        chains: dict[str, dict] = {}
        if spec.inventory == REAL_SHAPE_INVENTORY:
            _materialize_real_shape_inventory(trial_dir, spec)
        if spec.verdicts is not None:
            for verdict in spec.verdicts:
                chain = None
                if verdict.identified != "missed":
                    chain = _materialize_chain(files, trial_dir, spec, verdict)
                    chains[verdict.vuln_id] = chain
                rows.append(_verdict_row(spec, verdict, chain))
            _write_yaml(trial_dir / VERDICTS_FILENAME, rows)

        if spec.diagnoses:
            diagnoses = [_diagnosis_row(spec, row, chains) for row in spec.diagnoses]
            _write_yaml(trial_dir / DIAGNOSES_FILENAME, diagnoses)

        snapshot = None
        if spec.verdicts:
            if spec.inventory == REAL_SHAPE_INVENTORY:
                snapshot = _capture_project_snapshot(
                    files, trial_dir, spec, _real_shape_unit_slugs()
                )
            else:
                snapshot = _materialize_project_snapshot(files, trial_dir, spec, chains)

        manifest = artifact_store.build_run_manifest(
            _record(spec),
            artifact_store._chain_sources(rows),
            DEMO_COPIED_AT,
            diagnoses_present=bool(spec.diagnoses),
            project_snapshot=snapshot,
        )
        if snapshot is not None:
            # The schema-v2 fingerprint is computed from the exact staged bytes
            # (Task 3 helper); it is embedded in both available sections.
            fingerprint = artifact_store._snapshot_sha256(trial_dir, manifest, files)
            manifest["project_snapshot"]["snapshot_sha256"] = fingerprint
            manifest["project_artifacts"]["snapshot_sha256"] = fingerprint
        _write_yaml(trial_dir / MANIFEST_FILENAME, manifest)
    return root


def main(argv: Sequence[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        description="Generate a synthetic eval store for the /eval demo pages."
    )
    parser.add_argument(
        "--output",
        default=DEFAULT_OUTPUT,
        help="destination directory (default: %(default)s)",
    )
    args = parser.parse_args(argv)
    root = generate(args.output)
    print(instructions(root))
    return 0


